"""URDF exporter (P1 T1.8, plan §5.1, P1 §4.5): plan + built parts + assembly check -> ROS 2 description package.

    export_package(plan, parts, check, io_dir, out_dir, robot)
      <out_dir>/<robot>_description/
        package.xml, CMakeLists.txt
        urdf/<robot>.urdf
        meshes/visual/<owner>.stl      link frame, metres
        meshes/collision/<owner>.stl   only for owners whose bbox is a poor fit (volume ratio < 0.7)
      <out_dir>/print/<part>.stl       printed parts in their own frame, mm (for the slicer)

Mapping:
  link      one rigid group: owners joined by component attaches and plan `fixed` joints; named after
            the owner nearest the ground (the group root). A servo body belongs to the link it is mounted on.
  frames    root link = ground owner frame; child link = its joint connector frame (child side), so every
            joint has axis 0 0 1 and origin = parent connector pose in the parent link frame (D13)
  joints    revolute / continuous / gears -> revolute|continuous; slider / rack_pinion -> prismatic (m);
            mimic -> <mimic>; cylindrical / ball are not exported in P1 (failure signal)
  limits    plan limits; effort/velocity "from_card" = stall@6V x derating x servos_on_axis, speed@6V
  inertial  per owner: mass (printed model or card), inertia = solid tensor x mass / volume (density 1
            tensor from the sweep), rotated into the link frame and combined with the parallel-axis rule
  collision box primitive when owner volume / bbox volume >= 0.7, else the visual mesh
  tool0     fixed link at the plan's `tool` connector
"""
import math
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from xml.sax.saxutils import quoteattr

import numpy as np
import trimesh

from assembly.builder import card_model
from assembly.kinematics import LINEAR, ROTARY, Tree, inv, mul
from components.card import load_card
from harness.run import run_request
from schemas.plan import AssemblyPlan
from schemas.signal import Signal
from validate.assembly_check import AssemblyCheck
from validate.masses import actuator_limit
from validate.plan_check import tool_connectors

BOX_FILL = 0.7
GATE = "export"


@dataclass
class ExportResult:
    ok: bool
    signals: list[Signal]
    package: str | None = None
    urdf: str | None = None
    links: dict = field(default_factory=dict)     # link -> {owners, mass_kg, com_m}
    joints: dict = field(default_factory=dict)    # joint -> {type, parent, child}
    print_stl: dict = field(default_factory=dict)


def _f(v):
    return "%.12g" % (0.0 if abs(v) < 1e-15 else v)


def rpy(r):
    """URDF rpy (R = Rz(yaw) Ry(pitch) Rx(roll)) of a 3x3 rotation."""
    pitch = math.asin(max(-1.0, min(1.0, -r[2][0])))
    if abs(r[2][0]) < 1 - 1e-9:
        return math.atan2(r[2][1], r[2][2]), pitch, math.atan2(r[1][0], r[0][0])
    return math.atan2(-r[1][2], r[1][1]), pitch, 0.0


def origin_xml(t, scale=1e-3):
    r = [row[:3] for row in t[:3]]
    return '<origin xyz="%s %s %s" rpy="%s %s %s"/>' % (*(_f(t[i][3] * scale) for i in range(3)), *(_f(a) for a in rpy(r)))


def rigid_groups(tree):
    """owner -> group root (the owner nearest the ground in its rigid group)."""
    root = {tree.ground: tree.ground}
    for e in tree.edges:                       # root -> leaf order
        rigid = e.kind == "attach" or e.jtype == "fixed"
        root[e.child] = root[e.parent] if rigid else e.child
    return root


def link_inertial(owners, masses, props, local):
    """Combined (mass kg, com mm, inertia kg.mm^2 about com) in the link frame."""
    items = []
    for o in owners:
        m = masses.get(o, {}).get("mass_kg", 0.0)
        if m <= 0:
            continue
        t = np.array(local[o])
        R, p = t[:3, :3], t[:3, 3]
        pr = props.get(o)
        if pr and pr["volume_mm3"] > 0:
            I = np.array(pr["inertia_mm5"]) * m / pr["volume_mm3"]
        else:
            I = np.zeros((3, 3))
        c = np.array(masses[o]["com_mm"])
        items.append((m, R @ c + p, R @ I @ R.T))
    M = sum(m for m, _, _ in items)
    if M <= 0:
        return 0.0, np.zeros(3), np.zeros((3, 3))
    com = sum(m * c for m, c, _ in items) / M
    I = np.zeros((3, 3))
    for m, c, Ic in items:
        d = c - com
        I += Ic + m * (d @ d * np.eye(3) - np.outer(d, d))
    return M, com, I


def _package_files(pkg: Path, robot: str):
    name = robot + "_description"
    (pkg / "package.xml").write_text(f"""<?xml version="1.0"?>
<package format="3">
  <name>{name}</name>
  <version>0.0.1</version>
  <description>{robot}: generated by AgenticCAD</description>
  <maintainer email="noreply@example.com">AgenticCAD</maintainer>
  <license>Apache-2.0</license>
  <buildtool_depend>ament_cmake</buildtool_depend>
  <exec_depend>urdf</exec_depend>
  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
""", encoding="utf-8")
    (pkg / "CMakeLists.txt").write_text(f"""cmake_minimum_required(VERSION 3.8)
project({name})
find_package(ament_cmake REQUIRED)
install(DIRECTORY urdf meshes DESTINATION share/${{PROJECT_NAME}})
ament_package()
""", encoding="utf-8")


def export_package(plan: AssemblyPlan, parts: dict[str, Path], check: AssemblyCheck, io_dir: Path, out_dir: Path,
                   robot: str = "robot", timeout_s: float = 180.0) -> ExportResult:
    sigs: list[Signal] = []
    out_dir = Path(out_dir).resolve()
    pkg_name = robot + "_description"
    pkg = out_dir / pkg_name
    if pkg.exists():
        shutil.rmtree(pkg)
    for d in ("urdf", "meshes/visual", "meshes/collision"):
        (pkg / d).mkdir(parents=True, exist_ok=True)
    _package_files(pkg, robot)

    pd = plan.model_dump()
    tree = Tree(pd, check.frames, check.mounts)
    if not tree.ok:
        return ExportResult(False, [Signal(level="failure", gate=GATE, cause=s["cause"], location=s["location"])
                                    for s in tree.signals])
    cards = {c.card: load_card(c.card) for c in plan.components}
    comp_card = {c.id: c.card for c in plan.components}

    # meshes in owner frames (mm): parts + card models; envelopes get box visuals from their bbox
    sources = {k: str(Path(v).resolve()) for k, v in parts.items()}
    for c in plan.components:
        m = card_model(c.card)
        if m:
            sources[c.id] = m
    raw_dir = Path(io_dir).resolve() / "meshes_raw"
    res = run_request({"op": "mesh_parts", "meshes": sources, "out_dir": str(raw_dir)}, io_dir, timeout_s=timeout_s)
    sigs += [Signal.from_worker(s) for s in res.signals]
    meshes = res.result or {}

    group = rigid_groups(tree)
    world0 = tree.fk(tree.joint_values({})[0])
    link_world = {tree.ground: world0[tree.ground]}
    joints_xml, out_joints = [], {}
    for e in tree.edges:
        if e.kind == "attach" or e.jtype == "fixed":
            continue
        if e.jtype not in ROTARY | LINEAR or e.jtype == "cylindrical":
            sigs.append(Signal(level="failure", gate=GATE, location="plan.joints.%s" % e.name,
                               cause="joint %r: type %s is not exported in P1" % (e.name, e.jtype),
                               action="use revolute, continuous, slider, gears or rack_pinion"))
            continue
        link_world[e.child] = mul(world0[e.child], tree.frames[e.child][e.cconn])
        parent_link = group[e.parent]
        jo = mul(inv(link_world[parent_link]), mul(world0[e.parent], tree.frames[e.parent][e.pconn]))
        j = e.joint
        lim = j.get("limits")
        linear = e.jtype in LINEAR
        if e.jtype == "continuous" or (e.jtype == "gears" and not lim):
            utype = "continuous"
        else:
            utype = "prismatic" if linear else "revolute"
        lines = ['  <joint name=%s type="%s">' % (quoteattr(e.name), utype),
                 '    <parent link=%s/>' % quoteattr(parent_link), '    <child link=%s/>' % quoteattr(e.child),
                 "    " + origin_xml(jo), '    <axis xyz="0 0 1"/>']
        if lim or j.get("driver"):
            effort, velocity = (lim or {}).get("effort", "from_card"), (lim or {}).get("velocity", "from_card")
            card = cards.get(comp_card.get(j.get("driver")), {})
            if "from_card" in (effort, velocity):
                al = actuator_limit(card, j.get("servos_on_axis", 1))
                if al is None or linear:
                    sigs.append(Signal(level="failure", gate=GATE, location="plan.joints.%s" % e.name,
                                       cause="joint %r: effort/velocity 'from_card' but driver %r has no rotary rating"
                                             % (e.name, j.get("driver")), action="give numeric effort and velocity"))
                    al = (0.0, 0.0, 0.0)
                if effort == "from_card":
                    effort = al[0]
                if velocity == "from_card":
                    velocity = ((card.get("actuation") or {}).get("speed_rad_s") or {}).get("at_6V", 0.0)
            s = 1e-3 if linear else 1.0
            bounds = ' lower="%s" upper="%s"' % (_f(lim["lower"] * s), _f(lim["upper"] * s)) if lim and utype != "continuous" else ""
            lines.append('    <limit%s effort="%s" velocity="%s"/>' % (bounds, _f(effort), _f(velocity * s)))
        if j.get("mimic"):
            m = j["mimic"]
            off = m["offset"] * (1e-3 if linear else 1.0)
            lines.append('    <mimic joint=%s multiplier="%s" offset="%s"/>' % (quoteattr(m["joint"]), _f(m["multiplier"]), _f(off)))
        lines.append("  </joint>")
        joints_xml.append("\n".join(lines))
        out_joints[e.name] = {"type": utype, "parent": parent_link, "child": e.child}

    # links
    members = {}
    for o, root in group.items():
        members.setdefault(root, []).append(o)
    local = {o: mul(inv(link_world[group[o]]), world0[o]) for o in group if group[o] in link_world}
    links_xml, out_links = [], {}
    for root, owners in members.items():
        if root not in link_world:
            continue
        M, com, I = link_inertial(owners, check.masses, check.owners, local)
        lines = ["  <link name=%s>" % quoteattr(root)]
        if M > 0:
            Im = I * 1e-6
            lines += ["    <inertial>", '      <origin xyz="%s %s %s" rpy="0 0 0"/>' % tuple(_f(v * 1e-3) for v in com),
                      '      <mass value="%s"/>' % _f(M),
                      '      <inertia ixx="%s" ixy="%s" ixz="%s" iyy="%s" iyz="%s" izz="%s"/>'
                      % tuple(_f(v) for v in (Im[0, 0], Im[0, 1], Im[0, 2], Im[1, 1], Im[1, 2], Im[2, 2])),
                      "    </inertial>"]
        for o in sorted(owners):
            t = np.array(local[o])
            props = check.owners.get(o)
            if o in meshes:
                mesh = trimesh.load_mesh(meshes[o]["stl"])
                mesh.apply_transform(t)
                mesh.apply_scale(1e-3)
                mesh.export(pkg / "meshes" / "visual" / (o + ".stl"))
                uri = "package://%s/meshes/visual/%s.stl" % (pkg_name, o)
                lines += ["    <visual name=%s>" % quoteattr(o), '      <geometry><mesh filename="%s"/></geometry>' % uri, "    </visual>"]
            if not props:
                continue
            bb = props["bbox"]
            size = [bb[i + 3] - bb[i] for i in range(3)]
            centre = [(bb[i + 3] + bb[i]) / 2 for i in range(3)]
            fill = props["volume_mm3"] / max(1e-9, size[0] * size[1] * size[2])
            box_t = mul(local[o], [[1, 0, 0, centre[0]], [0, 1, 0, centre[1]], [0, 0, 1, centre[2]], [0, 0, 0, 1]])
            box = ('      <geometry><box size="%s %s %s"/></geometry>' % tuple(_f(v * 1e-3) for v in size))
            if o not in meshes:   # envelope: box visual too
                lines += ["    <visual name=%s>" % quoteattr(o), "      " + origin_xml(box_t), box, "    </visual>"]
            if fill >= BOX_FILL or o not in meshes:
                lines += ["    <collision name=%s>" % quoteattr(o), "      " + origin_xml(box_t), box, "    </collision>"]
            else:
                shutil.copy(pkg / "meshes" / "visual" / (o + ".stl"), pkg / "meshes" / "collision" / (o + ".stl"))
                uri = "package://%s/meshes/collision/%s.stl" % (pkg_name, o)
                lines += ["    <collision name=%s>" % quoteattr(o), '      <geometry><mesh filename="%s"/></geometry>' % uri,
                          "    </collision>"]
        lines.append("  </link>")
        links_xml.append("\n".join(lines))
        out_links[root] = {"owners": sorted(owners), "mass_kg": M, "com_m": (com * 1e-3).tolist()}

    tools = tool_connectors(plan)
    if len(tools) == 1:
        owner, conn = tools[0].split(".")
        if group.get(owner) in link_world:
            t = mul(local[owner], tree.frames[owner][conn])
            links_xml.append('  <link name="tool0"/>')
            joints_xml.append('  <joint name="tool0_joint" type="fixed">\n    <parent link=%s/>\n    <child link="tool0"/>\n    %s\n  </joint>'
                              % (quoteattr(group[owner]), origin_xml(t)))

    urdf = pkg / "urdf" / (robot + ".urdf")
    urdf.write_text('<?xml version="1.0"?>\n<!-- Generated by AgenticCAD (P1 exporter): metres, kg, rad. Link frame = its joint '
                    'connector frame; joint axes are 0 0 1. -->\n<robot name=%s>\n%s\n\n%s\n</robot>\n'
                    % (quoteattr(robot), "\n".join(links_xml), "\n".join(joints_xml)), encoding="utf-8")

    print_dir = out_dir / "print"
    print_dir.mkdir(exist_ok=True)
    print_stl = {}
    for p in plan.parts:
        if p.name in meshes:
            dst = print_dir / (p.name + ".stl")
            shutil.copy(meshes[p.name]["stl"], dst)
            print_stl[p.name] = str(dst)
    ok = res.ok and not any(s.level == "failure" for s in sigs)
    return ExportResult(ok, sigs, str(pkg), str(urdf), out_links, out_joints, print_stl)
